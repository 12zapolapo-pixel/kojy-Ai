// Builds packages/shared/src/projects/templates.ts from packages/shared/templates/*/bot.py
// (the starter bots in Bot Studio). Run after editing a template:
//   node scripts/gen-templates.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../packages/shared/templates/", import.meta.url);
const common = readFileSync(new URL("_common.py", dir), "utf8").trim();

// id → what the Studio shows and how Kojy tests it.
const META = {
  starter:    { name: "Starter",         emoji: "✨", cls: "StarterBot",    desc: "The smallest working bot — tell Kojy what to add.", tryChat: ["!ping"] },
  greeter:    { name: "Greeter",         emoji: "👋", cls: "GreeterBot",    desc: "Welcomes everyone who joins, waves, says goodbye.", tryChat: ["!hello"], join: true },
  moderation: { name: "Moderation",      emoji: "🛡️", cls: "ModerationBot", desc: "Mutes banned words, kicks after 3 warnings. Needs moderator rights.", tryChat: ["!help"] },
  tips:       { name: "Tip Rewards",     emoji: "💛", cls: "TipBot",        desc: "Thanks tippers and keeps a leaderboard (!top).", tryChat: ["!top"] },
  emotes:     { name: "Emote Commands",  emoji: "💃", cls: "EmoteBot",      desc: "!e <number> makes your avatar emote; !dance for a random dance.", tryChat: ["!e 1", "!dance"] },
  host:       { name: "Room Host",       emoji: "🎤", cls: "HostBot",       desc: "Welcomes people, timed announcements, !rules.", tryChat: ["!rules"], join: true },
  economy:    { name: "Economy",         emoji: "💰", cls: "EconomyBot",    desc: "Coins for chatting, !daily bonus, !give, !top.", tryChat: ["hi", "!daily", "!balance"] },
  trivia:     { name: "Trivia",          emoji: "❓", cls: "TriviaBot",     desc: "!trivia questions, points and a leaderboard.", tryChat: ["!trivia", "!leaderboard"] },
  voice:      { name: "Voice Manager",   emoji: "🎙️", cls: "VoiceBot",      desc: "Owner can check voice chat and invite or remove speakers.", tryChat: ["!help"] },
};

const templates = Object.entries(META).map(([id, m]) => {
  const code = readFileSync(new URL(`${id}/bot.py`, dir), "utf8").replace("#COMMON#", common);
  if (!code.includes(`class ${m.cls}(BaseBot)`)) throw new Error(`${id}: class ${m.cls} not found`);
  return { id, name: m.name, emoji: m.emoji, description: m.desc, entrypoint: `bot:${m.cls}`, tryChat: m.tryChat, join: !!m.join, files: { "bot.py": code } };
});

writeFileSync(new URL("../packages/shared/src/projects/templates.ts", import.meta.url), `// GENERATED by scripts/gen-templates.mjs from packages/shared/templates — edit those, then re-run.
/* eslint-disable */

export interface BotTemplate {
  id: string; name: string; emoji: string; description: string; entrypoint: string;
  /** Chat lines Kojy uses to test it in the fake room. */
  tryChat: string[]; join: boolean;
  files: Record<string, string>;
}

export const BOT_TEMPLATES: BotTemplate[] = ${JSON.stringify(templates, null, 2)};
`);
console.log(`wrote ${templates.length} templates`);
